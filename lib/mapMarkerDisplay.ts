// 카카오맵 확대/축소 레벨에 따라 캠퍼스 고정지점 마커에 이름을 보여줄지 판단하는 순수 함수.
//
// 왜 레벨 5부터 숨기는가 (근거):
// 1) 카카오맵 레벨↔축척 대응은 레벨이 1 오를 때마다 축척이 정확히 2배가 되는 계단이다
//    (카카오 데브톡 공식 안내 https://devtalk.kakao.com/t/topic/35624 의 "10m=1:475,
//    20m=1:950, 30m=1:1900, 50m=1:3800, 100m=1:7600, 250m=1:15200, 500m=1:30400 ..."
//    표는 각 항목이 정확히 직전 항목의 2배 축척이다). 이 프로젝트가 쓰는 지도 초기
//    레벨 3이 통상 "50m" 축척으로 알려져 있다는 점(체감상 동네 블록 스케일)과 맞춰
//    역산하면: 레벨1=20m, 레벨2=30m, 레벨3=50m, 레벨4=100m, 레벨5=250m, 레벨6=500m.
//    (CampusRouteMap.tsx의 MAX_MAP_LEVEL=6·초기 level=3과 일치)
// 2) 캠퍼스 고정지점 7곳의 실좌표(lib/supabase.ts LOCATION_POINTS, Haversine 계산)로
//    가장 가까운 쌍들은 111.8m(가천대역_1번출구↔가천대학교_정문), 120.4m(중앙도서관↔
//    학생회관), 125.1m(교육대학원↔중앙도서관), 134.9m(AI공학관↔제2기숙사) — 즉 4쌍이
//    110~135m 대역에 몰려 있고, 가장 먼 쌍은 988.0m(가천대역_1번출구↔제2기숙사)다.
// 3) 지도 스케일 컨트롤의 기준 폭을 대략 100px로 두면 (레벨의 축척값 ÷ 100)이
//    대략적인 m/px이 된다. 가장 가까운 쌍(111.8m)을 기준으로 레벨별 화면 간격을
//    추정하면:
//      레벨4 (100m/100px = 1px/m): 111.8m → 화면상 약 112px 간격.
//        말풍선(shortLabel+개수, 실측 ~70~140px)이 겹치지 않고 버틸 수 있는 한계.
//      레벨5 (250m/100px = 0.4px/m): 111.8m → 약 45px 간격.
//        말풍선 폭에 크게 못 미쳐 겹친다.
//      레벨6 (500m/100px = 0.2px/m): 111.8m → 약 22px 간격.
//        완전히 겹친다.
//    즉 실제로 겹치기 시작하는 지점은 레벨 5(가장 축소 상태에서 한 단계 확대)부터이고,
//    이는 사용자가 보고한 "가장 축소한 상태와 거기서 한 단계 확대한 상태"(레벨6·레벨5)
//    와 정확히 일치한다.
// 4) 따라서 레벨 1~4에서는 이름을 보여주고, 레벨 5~6에서는 핀 + 방 개수만 보여준다.
export const MAP_LABEL_HIDE_LEVEL = 5

export function shouldShowMarkerNames(level: number): boolean {
  return level < MAP_LABEL_HIDE_LEVEL
}
